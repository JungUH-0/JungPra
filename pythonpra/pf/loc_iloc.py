import pandas as pd

df = pd.DataFrame({
    "label": ["ㄱ", "ㄴ", "ㄷ", "ㄹ", "ㅁ", "ㅂ"],
    "frame_count": [30, 28, 32, 25, 40, 22],
    "confidence": [0.95, 0.88, 0.99, 0.75, 0.91, 0.60]
}, index=[10, 20, 30, 40, 50, 60])   # 일부러 인덱스를 10,20,30... 으로 지정

print(df)
print("#####################")

print(df.loc[10])     # 인덱스 "이름"이 10인 행 -> 맨 첫 줄 (ㄱ)
print("#####################")

print(df.iloc[0])      # "위치" 0번째 행 -> 역시 맨 첫 줄 (ㄱ), 우연히 같음
print("#####################")

print(df.loc[30])     # 인덱스 이름이 30인 행 -> ㄷ
print("#####################")
#print(df.iloc[30])     # 위치 30번째 행? -> 에러! 행이 6개뿐이라 위치 30은 존재 안 함


print(df.loc[10:30])    # 이름 10부터 30까지 -> 끝(30) 포함됨!
print("#####################")

print(df.iloc[0:2])      # 위치 0부터 2 "직전"까지 -> 끝(2) 미포함, 즉 0,1번만
print("#####################")

print(df.loc[10, "label"])      # 이름이 10인 행의 label 값 -> "ㄱ"
print("#####################")

print(df.iloc[0, 0])              # 위치 0행 0열 -> "ㄱ"  (numpy mat[0,0]이랑 똑같은 방식)
print("#####################")

print(df.loc[10:30, "confidence"])   # 여러 행 + 특정 열
print("#####################")

print(df.iloc[0:2, 1])           # 위치 기준 여러 행 + 0번째 열
print("#####################")

print(df.loc[df["confidence"] < 0.9, "label"])
# confidence가 0.9보다 큰 행들만, 그 중 label 열만